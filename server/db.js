import { DatabaseSync } from 'node:sqlite';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DB_PATH = path.join(__dirname, 'data', 'ekonomi-desa.db');

export const db = new DatabaseSync(DB_PATH);
db.exec('PRAGMA foreign_keys = ON;');

db.exec(`
CREATE TABLE IF NOT EXISTS desa (
  kode_desa TEXT PRIMARY KEY,
  provinsi TEXT,
  kabupaten TEXT,
  kecamatan TEXT,
  nama_desa TEXT,
  status_desa TEXT,
  lat REAL,
  lng REAL,
  tahun INTEGER
);
`);

// Composite Indeks Desa score (from the master sheet's "NILAI ID 2026" column,
// Kemendes's own computed value - not calculated by this app). Added after
// the initial schema, so it needs an explicit migration guard rather than
// just widening the CREATE TABLE above (which is a no-op on an existing db).
const desaColumns = db.prepare("PRAGMA table_info(desa)").all().map((c) => c.name);
if (!desaColumns.includes('nilai_indeks_desa')) {
  db.exec('ALTER TABLE desa ADD COLUMN nilai_indeks_desa REAL;');
}

db.exec(`

CREATE TABLE IF NOT EXISTS skor_indikator (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  kode_desa TEXT NOT NULL REFERENCES desa(kode_desa),
  tahun INTEGER,
  dimensi TEXT,
  sub_dimensi TEXT,
  nama_indikator TEXT,
  skor REAL,
  bobot_maks REAL
);
CREATE INDEX IF NOT EXISTS idx_skor_desa ON skor_indikator(kode_desa);

CREATE TABLE IF NOT EXISTS jawaban_kuesioner (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  kode_desa TEXT NOT NULL REFERENCES desa(kode_desa),
  tahun INTEGER,
  pertanyaan TEXT,
  jawaban TEXT
);
CREATE INDEX IF NOT EXISTS idx_jawaban_desa ON jawaban_kuesioner(kode_desa);

CREATE TABLE IF NOT EXISTS potensi_desa (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  kode_desa TEXT NOT NULL REFERENCES desa(kode_desa),
  tahun INTEGER,
  sektor TEXT,
  subsektor TEXT,
  nilai TEXT
);
CREATE INDEX IF NOT EXISTS idx_potensi_desa ON potensi_desa(kode_desa);
CREATE INDEX IF NOT EXISTS idx_potensi_sektor ON potensi_desa(sektor);

CREATE TABLE IF NOT EXISTS ekosistem_desa (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  kode_desa TEXT NOT NULL REFERENCES desa(kode_desa),
  tahun INTEGER,
  komponen TEXT,
  nilai TEXT
);
CREATE INDEX IF NOT EXISTS idx_ekosistem_desa ON ekosistem_desa(kode_desa);

CREATE TABLE IF NOT EXISTS import_log (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  sumber_file TEXT,
  sheet TEXT,
  waktu_import TEXT,
  jumlah_baris INTEGER
);

-- Cached AI recommendations, keyed by desa + a hash of the input data used
-- to generate them. Re-importing data or re-running with a newer prompt
-- naturally invalidates old cache rows (new input_hash) without needing an
-- explicit migration; old rows are just never looked up again.
CREATE TABLE IF NOT EXISTS rekomendasi_produk (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  kode_desa TEXT NOT NULL REFERENCES desa(kode_desa),
  input_hash TEXT NOT NULL,
  model TEXT,
  rekomendasi_json TEXT,
  dibuat_pada TEXT
);
CREATE INDEX IF NOT EXISTS idx_rekomendasi_desa ON rekomendasi_produk(kode_desa, input_hash);

-- Same caching pattern as rekomendasi_produk, but for the kabupaten-level
-- BUMDes-condition analysis (aggregated across all desa in that kabupaten).
CREATE TABLE IF NOT EXISTS rekomendasi_kabupaten (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  kabupaten TEXT NOT NULL,
  input_hash TEXT NOT NULL,
  model TEXT,
  rekomendasi_json TEXT,
  dibuat_pada TEXT
);
CREATE INDEX IF NOT EXISTS idx_rekomendasi_kab ON rekomendasi_kabupaten(kabupaten, input_hash);

-- Single-use invitation codes, generated by an admin and handed out
-- out-of-band (WhatsApp/surat). Deliberately NOT the real kode_desa/
-- kabupaten values - those are public data already visible throughout the
-- app, so using them as a login credential would let anyone self-register
-- as any village.
CREATE TABLE IF NOT EXISTS kode_registrasi (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  kode TEXT UNIQUE NOT NULL,
  role TEXT NOT NULL CHECK(role IN ('desa','kabupaten','provinsi','admin')),
  kode_desa TEXT REFERENCES desa(kode_desa),
  kabupaten TEXT,
  dibuat_oleh TEXT,
  dibuat_pada TEXT NOT NULL,
  dipakai_oleh_user_id INTEGER,
  dipakai_pada TEXT
);
CREATE INDEX IF NOT EXISTS idx_kode_registrasi_kode ON kode_registrasi(kode);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  email TEXT UNIQUE NOT NULL,
  nama TEXT,
  role TEXT NOT NULL CHECK(role IN ('desa','kabupaten','provinsi','admin')),
  kode_desa TEXT REFERENCES desa(kode_desa),
  kabupaten TEXT,
  dibuat_pada TEXT NOT NULL,
  login_terakhir TEXT
);
`);
